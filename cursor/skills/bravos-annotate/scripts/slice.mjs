#!/usr/bin/env node
// @comment -- "Entry for bravos-annotate: gathers git diff, guardlink worklist/coverage and open PRs via read-only spawnSync calls, runs pickSlice and prints bravos.slice/v2 JSON (coverage, coverage_detail, batches, tiers); dependency-free, copied verbatim into target repos."
import { spawnSync } from 'node:child_process';
import { closeSync, openSync, readSync } from 'node:fs';
import { join } from 'node:path';
import { pickSlice } from './lib/pick.mjs';

/** Read-only spawnSync wrapper (no shell, timeout, bounded buffer); mirrors hooks/lib/briefing.mjs runJson. */
function runJson(cmd, args, { cwd, timeoutMs = 10000, env = process.env } = {}) {
  const r = spawnSync(cmd, args, { cwd, env, timeout: timeoutMs, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
  if (r.error) {
    if (r.error.code === 'ETIMEDOUT') return { ok: false, error: `${cmd}: timed out after ${timeoutMs / 1000}s` };
    return { ok: false, error: `${cmd}: ${r.error.code ?? r.error.message}` };
  }
  if (r.status !== 0) return { ok: false, error: `${cmd} exited ${r.status}` };
  try {
    return { ok: true, json: JSON.parse(r.stdout) };
  } catch {
    return { ok: false, error: `${cmd}: output was not JSON` };
  }
}

function usage(msg) {
  process.stderr.write(`slice.mjs: ${msg} (usage: slice.mjs [--base <ref>] [--n <int>=5] [--batches <int>=1] [--prefer <file>]... [--deep] [--json])\n`);
  process.exit(2);
}

function parseArgs(argv) {
  const o = { base: null, n: 5, batches: 1, prefer: [], deep: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--deep') o.deep = true;
    else if (a === '--json') continue;
    else if (a === '--base') {
      o.base = argv[++i];
      if (!o.base) usage('--base needs a ref');
    } else if (a === '--n') {
      const v = argv[++i];
      if (v === undefined || !/^\d+$/.test(v) || Number(v) < 1) usage('--n needs an integer >= 1');
      o.n = Number(v);
    } else if (a === '--batches') {
      const v = argv[++i];
      if (v === undefined || !/^\d+$/.test(v) || Number(v) < 1) usage('--batches needs an integer >= 1');
      o.batches = Number(v);
    } else if (a === '--prefer') {
      const v = argv[++i];
      if (!v || v.startsWith('--')) usage('--prefer needs a file path');
      o.prefer.push(v);
    } else usage(`unknown argument ${a}`);
  }
  return o;
}

const paths = (v) => (Array.isArray(v) ? v : []).map((e) => (typeof e === 'string' ? e : (e?.path ?? e?.file))).filter((p) => typeof p === 'string');

const opts = parseArgs(process.argv.slice(2));
const cwd = process.cwd();
const notes = [];

let base = opts.base;
if (!base) {
  const r = spawnSync('git', ['symbolic-ref', '-q', '--short', 'refs/remotes/origin/HEAD'], { cwd, encoding: 'utf8', timeout: 10000, stdio: ['ignore', 'pipe', 'ignore'] });
  base = r.status === 0 && r.stdout.trim() ? r.stdout.trim() : 'origin/main';
}

let changed = [];
const d = spawnSync('git', ['diff', '--name-only', '--diff-filter=ACMR', `${base}...HEAD`], { cwd, encoding: 'utf8', timeout: 10000, maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
if (d.error || d.status !== 0) {
  const why = d.error ? (d.error.code ?? d.error.message) : (d.stderr || '').trim().split('\n')[0] || `exited ${d.status}`;
  notes.push(`git diff failed: ${why}`);
} else {
  changed = d.stdout.split('\n').filter(Boolean);
}

const un = runJson('guardlink', ['unannotated', '--json'], { cwd });
if (!un.ok) {
  process.stderr.write(`slice.mjs: guardlink unannotated failed: ${un.error}\n`);
  process.exit(1);
}

let inFlight = [];
const gh = runJson('gh', ['pr', 'list', '--state', 'open', '--json', 'number,files', '--limit', '50'], { cwd });
if (gh.ok && Array.isArray(gh.json)) {
  inFlight = gh.json.map((p) => ({ pr: p.number, files: paths(p.files) }));
} else {
  notes.push('gh unavailable: in-flight PRs not checked');
}

let coverageBefore = null;
const ci = runJson('guardlink', ['ci', '-f', 'json'], { cwd });
const cov = ci.ok ? ci.json?.summary?.coverage : null;
if (cov) coverageBefore = { percent: cov.percent, annotated_files: cov.annotated_files, source_files: cov.source_files };
else notes.push('guardlink ci unavailable: coverage_before omitted');

// A file whose first 2 KB says it is generated ("Code generated ... DO NOT EDIT", "@generated") ranks last.
function isGenerated(rel) {
  let fd;
  try {
    fd = openSync(join(cwd, rel), 'r');
    const buf = Buffer.alloc(2048);
    const len = readSync(fd, buf, 0, 2048, 0);
    return /Code generated .*DO NOT EDIT|@generated\b|autogenerated|auto-generated/i.test(buf.toString('utf8', 0, len));
  } catch {
    return false;
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}
const worklistPaths = paths(un.json?.worklist);
const generated = worklistPaths.slice(0, 5000).filter(isGenerated);

const n = opts.deep ? Infinity : opts.n;
const picked = pickSlice({
  worklist: worklistPaths,
  annotated: paths(un.json?.annotated),
  excluded: paths(un.json?.excluded),
  changed,
  inFlight,
  ownedDirs: [],
  generated,
  prefer: opts.prefer,
  n,
  batches: opts.batches,
});

process.stdout.write(
  JSON.stringify({
    schema: 'bravos.slice/v2',
    base,
    n: opts.deep ? 'unbounded' : n,
    mode: opts.deep ? 'deep' : 'slice',
    diff: picked.diff,
    coverage: picked.coverage,
    coverage_detail: picked.coverage_detail,
    batches: picked.batches,
    tiers: picked.tiers,
    skipped: picked.skipped,
    coverage_before: coverageBefore,
    notes,
  }) + '\n',
);
